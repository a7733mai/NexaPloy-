"""Bench lifecycle on disk + compose (§2, §3).

A bench is ``<root>/benches/<bench>/`` holding the rendered
``docker-compose.yml``, its ``.env`` (§3.1), ``apps.json`` and the bind-mounted
``sites/``, ``logs/`` and ``redis-queue/`` directories. The canonical template
takes structure from Jinja (``bench``) and values from ``.env`` via ``${VAR}``,
so changing ``.env`` + ``up -d`` is enough for most changes; the agent still
re-renders the compose file on create/update so template upgrades land too.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

from .. import validation as v
from ..config import FRAPPE_UID, REDIS_UID, Settings, read_env_file
from ..fsutil import atomic_write, ensure_dir, write_if_changed
from ..render import render_compose
from .docker import Docker, Result

# Order in which .env keys are written (§3.1 + template extras).
ENV_ORDER = (
    "COMPOSE_PROJECT_NAME", "BENCH_NAME", "IMAGE", "FRAPPE_UID", "FRAPPE_GID",
    "REDIS_UID", "REDIS_GID", "TZ", "DB_HOST", "DB_PORT", "BACKEND_WORKERS",
    "BACKEND_CPUS", "BACKEND_MEM", "WORKER_CPUS", "WORKER_MEM",
)
# Keys the caller may not override through ``env`` (identity of the bench).
RESERVED_ENV = frozenset({"COMPOSE_PROJECT_NAME", "BENCH_NAME", "IMAGE"})

CONFIGURATOR_PROFILE = "configurator"


class BenchError(RuntimeError):
    pass


class BenchManager:
    def __init__(self, settings: Settings, docker: Docker, templates: Path | None = None):
        self.settings = settings
        self.docker = docker
        self.templates = templates

    # ---- paths -----------------------------------------------------------------
    @property
    def root(self) -> Path:
        return self.settings.benches_dir

    def path(self, bench: str) -> Path:
        return self.root / v.bench_name(bench)

    def compose_file(self, bench: str) -> Path:
        return self.path(bench) / "docker-compose.yml"

    def env_file(self, bench: str) -> Path:
        return self.path(bench) / ".env"

    def sites_dir(self, bench: str) -> Path:
        return self.path(bench) / "sites"

    def exists(self, bench: str) -> bool:
        p = self.path(bench)
        return (p / "docker-compose.yml").exists() or (p / ".env").exists()

    def require(self, bench: str) -> None:
        if not self.exists(bench):
            raise BenchError(f"bench {bench!r} does not exist")

    def names(self) -> list[str]:
        if not self.root.is_dir():
            return []
        return sorted(
            p.name for p in self.root.iterdir()
            if p.is_dir() and v.BENCH_RE.match(p.name) and (p / "docker-compose.yml").exists()
        )

    def assets_volume(self, bench: str) -> str:
        return f"{v.bench_name(bench)}_assets"

    # ---- .env --------------------------------------------------------------------
    def read_env(self, bench: str) -> dict[str, str]:
        return read_env_file(self.env_file(bench))

    def image(self, bench: str) -> str | None:
        return self.read_env(bench).get("IMAGE") or None

    def default_env(self, bench: str, image: str) -> dict[str, str]:
        d = self.settings.bench
        return {
            "COMPOSE_PROJECT_NAME": bench,
            "BENCH_NAME": bench,
            "IMAGE": image,
            "FRAPPE_UID": str(FRAPPE_UID),
            "FRAPPE_GID": str(FRAPPE_UID),
            "REDIS_UID": str(REDIS_UID),
            "REDIS_GID": str(REDIS_UID),
            "TZ": d.tz,
            "DB_HOST": d.db_host,
            "DB_PORT": str(d.db_port),
            "BACKEND_WORKERS": str(d.backend_workers),
            "BACKEND_CPUS": str(d.backend_cpus),
            "BACKEND_MEM": str(d.backend_mem),
            "WORKER_CPUS": str(d.worker_cpus),
            "WORKER_MEM": str(d.worker_mem),
        }

    @staticmethod
    def validate_env_overrides(env: Mapping[str, Any] | None) -> dict[str, str]:
        out: dict[str, str] = {}
        for key, value in (env or {}).items():
            v.env_key(key)
            if key in RESERVED_ENV:
                raise v.ValidationError(f"env {key} cannot be overridden")
            s = str(value)
            if any(c in s for c in "\n\r\x00"):
                raise v.ValidationError(f"env {key}: value must be a single line")
            out[key] = s
        return out

    @staticmethod
    def format_env(values: Mapping[str, str]) -> str:
        lines = ["# Generated by the Nexaploy agent (ARCHITECTURE.md §3.1).",
                 "# Edit via the agent API; manual edits survive but IMAGE is managed."]
        keys = [k for k in ENV_ORDER if k in values] + sorted(k for k in values if k not in ENV_ORDER)
        for k in keys:
            lines.append(f"{k}={values[k]}")
        return "\n".join(lines) + "\n"

    def write_env(self, bench: str, values: Mapping[str, str]) -> bool:
        return write_if_changed(self.env_file(bench), self.format_env(values), mode=0o600)

    def context(self, bench: str, env: Mapping[str, str]) -> dict[str, Any]:
        """Jinja context for the compose template (every §3.1 key)."""
        d = self.default_env(bench, env.get("IMAGE", ""))
        merged = {**d, **env}
        return {
            "bench": bench,
            "image": merged["IMAGE"],
            "frappe_uid": int(merged["FRAPPE_UID"]),
            "frappe_gid": int(merged["FRAPPE_GID"]),
            "redis_uid": int(merged["REDIS_UID"]),
            "redis_gid": int(merged["REDIS_GID"]),
            "tz": merged["TZ"],
            "db_host": merged["DB_HOST"],
            "db_port": int(merged["DB_PORT"]),
            "backend_workers": int(merged["BACKEND_WORKERS"]),
            "backend_cpus": merged["BACKEND_CPUS"],
            "backend_mem": merged["BACKEND_MEM"],
            "worker_cpus": merged["WORKER_CPUS"],
            "worker_mem": merged["WORKER_MEM"],
        }

    def render(self, bench: str) -> bool:
        """(Re)render docker-compose.yml from the current .env."""
        env = self.read_env(bench)
        if not env.get("IMAGE"):
            raise BenchError(f"bench {bench}: IMAGE missing from .env")
        content = render_compose(self.context(bench, env), self.templates)
        return write_if_changed(self.compose_file(bench), content, mode=0o644)

    # ---- directories ------------------------------------------------------------
    def ensure_dirs(self, bench: str) -> None:
        base = ensure_dir(self.path(bench), mode=0o755)
        ensure_dir(base / "sites", FRAPPE_UID, FRAPPE_UID, 0o755)
        ensure_dir(base / "logs", FRAPPE_UID, FRAPPE_UID, 0o755)
        ensure_dir(base / "redis-queue", REDIS_UID, REDIS_UID, 0o700)

    def write_apps_json(self, bench: str, apps_json: Any) -> bool:
        if apps_json is None:
            return False
        if isinstance(apps_json, str):
            apps_json = json.loads(apps_json)
        return write_if_changed(self.path(bench) / "apps.json", json.dumps(apps_json, indent=2) + "\n")

    # ---- compose operations -------------------------------------------------------
    def up(self, bench: str) -> Result:
        return self.docker.bench_compose(bench, "up", "-d", "--remove-orphans", timeout=900)

    def down(self, bench: str) -> Result:
        return self.docker.bench_compose(bench, "down", "--remove-orphans", timeout=600)

    def stop(self, bench: str) -> Result:
        return self.docker.bench_compose(bench, "stop", timeout=600)

    def restart(self, bench: str) -> Result:
        return self.docker.bench_compose(bench, "restart", timeout=600)

    def run_configurator(self, bench: str) -> Result:
        return self.docker.bench_compose(
            bench, "--profile", CONFIGURATOR_PROFILE, "run", "--rm", "-T", "configurator", timeout=600
        )

    # ---- sites -------------------------------------------------------------------
    def sites(self, bench: str) -> list[str]:
        d = self.sites_dir(bench)
        if not d.is_dir():
            return []
        return sorted(
            p.name for p in d.iterdir()
            if p.is_dir() and v.SITE_RE.match(p.name) and (p / "site_config.json").exists()
        )

    def find_site(self, site: str) -> str | None:
        """Bench hosting ``site`` (scan ``benches/*/sites/<s>/site_config.json``)."""
        v.site_name(site)
        for bench in self.names():
            if (self.sites_dir(bench) / site / "site_config.json").exists():
                return bench
        return None

    def info(self, bench: str, with_status: bool = True) -> dict[str, Any]:
        env = self.read_env(bench)
        data: dict[str, Any] = {
            "name": bench,
            "image": env.get("IMAGE"),
            "path": str(self.path(bench)),
            "sites": self.sites(bench),
        }
        if with_status:
            running = sorted(self.docker.running_services(bench))
            data["running_services"] = running
            data["status"] = "running" if "backend" in running else "stopped"
        return data

    def list(self, with_status: bool = True) -> list[dict[str, Any]]:
        return [self.info(b, with_status) for b in self.names()]

    def archive_dir(self) -> Path:
        return self.root / ".archived"

    def write_text(self, bench: str, name: str, content: str) -> None:
        atomic_write(self.path(bench) / name, content)
